# Tugas 4 - Variabel dan Tipe Data

# Integer : bilangan bulat
a = 7
# Float : bilangan pecahan / desimal
b = 3.14
# String : teks
c = "Unama"

print("Integer :", a, "->", type(a))
print("Float   :", b, "->", type(b))
print("String  :", c, "->", type(c))

# Aturan penamaan variabel:
# - harus diawali huruf, tidak boleh pakai spasi/simbol
# - pemisah kata gunakan underscore (_)
# - huruf besar dan kecil dianggap berbeda
nama_mahasiswa = "Jackson"
Nama_Mahasiswa = "Berbeda dengan huruf kecil"
print(nama_mahasiswa)
print(Nama_Mahasiswa)
