# Latihan A - Soal 4: Menentukan apakah sebuah bilangan lebih besar dari 10
# Pseudocode ada di file dokumen (Word). Berikut penerjemahannya ke Python.

angka = float(input("Masukkan sebuah bilangan : "))
if angka > 10:
    print(angka, "lebih besar dari 10")
else:
    print(angka, "tidak lebih besar dari 10")
