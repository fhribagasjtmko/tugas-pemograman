# Latihan 2 - Mencari Luas Segitiga
# Rumus: L = 1/2 x alas x tinggi

print("=== Luas Segitiga ===")                         # 1. judul program
alas = float(input("Masukkan alas   : "))              # 2. input alas
tinggi = float(input("Masukkan tinggi : "))            # 3. input tinggi
luas = 0.5 * alas * tinggi                             # 4. proses: setengah x alas x tinggi
print("Luas segitiga =", luas)                         # 5. tampilkan hasil
